def _secured_apis_markdown(apis: dict[str, list[dict[str, Any]]], feature: str | None) -> str:
    total = sum(len(v) for v in apis.values())
    scope = f" matching '{feature}'" if feature else ""
    lines = [f"# Secured APIs ({total} in {len(apis)} feature(s){scope})", ""]
    if not apis:
        lines.append("No features matched.")
    for name in sorted(apis, key=str.lower):
        lines.append(f"## {name} ({len(apis[name])})")
        for api in apis[name]:
            lines.append(f"- {api.get('name') or '?'} ({api.get('api_id') or '?'})")
        lines.append("")
    return "\n".join(lines).rstrip()


def listen_path_pattern(listen_path: str) -> re.Pattern[str]:
    """The request paths a Tyk listen path claims, as an anchored prefix regex.

    A listen path is a gorilla-mux pattern: literal segments plus ``{...}``
    variables that each match one segment (``/crosswork/performance/v{.}/
    dashboards/`` claims ``/crosswork/performance/v1/dashboards/summary``).
    This is the conservative reading of how Tyk v5.1.1 routes (from its
    source, not observed live): ``gateway/api_loader.go`` sorts the API
    definitions by listen-path length, longest first, and registers each as a
    gorilla-mux path prefix, so the longest listen path that claims a request
    wins. Two details of this regex are stricter or looser than plain
    gorilla prefix matching: the match must end at a segment boundary (so
    ``/crosswork/aaa/`` does not claim ``/crosswork/aaaread/v1/role`` — gorilla
    only enforces that with ``enable_strict_routes``) and a trailing slash is
    optional (``/crosswork/inventory/`` claims ``/crosswork/inventory`` — a
    plain prefix would not). No template in the packaged map routes
    differently under either reading (tests/test_rbac_map.py checks). Matching
    is on the path only (no query string); the regex is a prefix (``match``,
    not ``fullmatch``) and the caller picks the longest match.
    """
    parts = [re.escape(part) for part in _LISTEN_VAR_RE.split(listen_path.rstrip("/"))]
    return re.compile("^" + "[^/]+".join(parts) + "(?=/|$)")


def load_rbac_map() -> dict[str, Any]:
    """The packaged tool -> API-requirement map (``cnc_mcp/data/rbac_map.json``)."""
